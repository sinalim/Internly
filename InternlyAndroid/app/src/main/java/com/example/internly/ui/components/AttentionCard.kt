import com.example.internly.ui.theme.Grey

@Composable
fun AttentionCard(
    company: String,
    tag: String,
    note: String,
    color: Color,
    icon: ImageVector,
) {
    Card(
        modifier = Modifier
            .fillMaxWidth()
            .padding(bottom = 10.dp),
        shape = RoundedCornerShape(12.dp),
        colors = CardDefaults.cardColors(containerColor = Color.White),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp),
    ) {
        Row(
            modifier = Modifier.padding(12.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Box(
                modifier = Modifier
                    .size(34.dp)
                    .background(color, CircleShape),
                contentAlignment = Alignment.Center,
            ) {
                Icon(icon, contentDescription = null, tint = Color.White, modifier = Modifier.size(18.dp))
            }
            Spacer(Modifier.width(12.dp))
            Column(modifier = Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(2.dp)) {
                Text(company, fontSize = 14.sp, fontWeight = FontWeight.Bold)
                Text(tag, fontSize = 11.sp, color = color, fontWeight = FontWeight.SemiBold)
                Text(note, fontSize = 12.sp, color = Grey)
            }
            Icon(Icons.Filled.ChevronRight, contentDescription = null, tint = Grey)
        }
    }
}
